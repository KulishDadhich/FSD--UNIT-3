CREATE TABLE account(email varchar(255) PRIMARY KEY, password_hash varchar(255) NOT NULL, role varchar(255));
CREATE TABLE post_event(
 event_id varchar(255) PRIMARY KEY, post_id varchar(255) NOT NULL UNIQUE,
 title varchar(255), content varchar(5000), platform varchar(255), event_type varchar(255), topic varchar(255), failure_mode varchar(255), status varchar(255),
 scheduled_at timestamptz, created_at timestamptz, processed_at timestamptz, next_retry_at timestamptz, dlq_at timestamptz,
 attempts integer NOT NULL, cycle_attempts integer NOT NULL, generation integer NOT NULL, replays integer NOT NULL, duplicates integer NOT NULL, pending_copies integer NOT NULL,
 error_details varchar(1000), version bigint NOT NULL
);
CREATE INDEX due_posts ON post_event(status,scheduled_at);
CREATE TABLE activity(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,event_id varchar(255),stage varchar(255),attempt integer NOT NULL,generation integer NOT NULL,timestamp timestamptz,message varchar(1000));
CREATE INDEX event_history ON activity(event_id,id);
CREATE TABLE publication(event_id varchar(255) PRIMARY KEY,published_at timestamptz,result varchar(255));
